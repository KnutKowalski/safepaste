import Foundation
import AppKit

// MARK: - Datentypen

enum ItemKind: String {
  case text
  case richText
  case image
  case file
}

struct StoredContent: Codable {
  let type: String
  let value: Data
}

struct ClipboardRecord {
  let id: UUID
  let kind: ItemKind
  let contents: [StoredContent]
  let preview: String
  let fullText: String
  let sourceApp: String?
  let copiedAt: Date
}

struct DisplayItem: Identifiable {
  let id: String
  let kind: ItemKind
  let preview: String
  let fullText: String
  let sourceApp: String?
  let pinned: Bool
  let lastUsed: Date
  let copies: Int
  let contents: [StoredContent]
}

// MARK: - Pasteboard-Typen

extension NSPasteboard.PasteboardType {
  static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
  // Konvention: Kennzeichnet die Original-Quell-App (nspasteboard.org).
  static let nspasteboardSource = NSPasteboard.PasteboardType("org.nspasteboard.source")
  // Eigener Marker: verhindert, dass SafePaste seine eigene Rückkopie aufzeichnet.
  static let safepasteRestored = NSPasteboard.PasteboardType("org.safepaste.restored")
  static let jpegType = NSPasteboard.PasteboardType("public.jpeg")
  static let heicType = NSPasteboard.PasteboardType("public.heic")
}

// MARK: - Einstellungen (validiert!)

enum SearchMode: String, CaseIterable {
  case exact = "Exakt"
  case regex = "Regex"
  case fuzzy = "Fuzzy"
}

enum AppSettings {
  private static let d = UserDefaults.standard

  /// Immer 1...999 – der Maccy historySize=0-Crash ist hier konstruktiv unmöglich.
  static var historySize: Int {
    let raw = d.integer(forKey: "historySize")
    if raw == 0 { return 200 }
    return min(999, max(1, raw))
  }
  static func setHistorySize(_ value: Int) {
    d.set(min(999, max(1, value)), forKey: "historySize")
  }

  /// Immer 0.2...5.0 s – kein CPU-Spin mehr durch defaults write ... 0.
  static var checkInterval: TimeInterval {
    let raw = d.double(forKey: "checkInterval")
    if raw <= 0 { return 0.5 }
    return min(5.0, max(0.2, raw))
  }
  static func setCheckInterval(_ value: Double) {
    d.set(min(5.0, max(0.2, value)), forKey: "checkInterval")
  }

  static var pasteByDefault: Bool {
    get { d.bool(forKey: "pasteByDefault") }
    set { d.set(newValue, forKey: "pasteByDefault") }
  }
  static var clearOnQuit: Bool {
    get { d.bool(forKey: "clearOnQuit") }
    set { d.set(newValue, forKey: "clearOnQuit") }
  }
  static var searchMode: SearchMode {
    if let raw = d.string(forKey: "searchMode"), let mode = SearchMode(rawValue: raw) {
      return mode
    }
    return .exact
  }
  static func setSearchMode(_ mode: SearchMode) {
    d.set(mode.rawValue, forKey: "searchMode")
  }

  static var ignoredApps: [String] {
    get { d.stringArray(forKey: "ignoredApps") ?? [] }
    set { d.set(newValue, forKey: "ignoredApps") }
  }

  static var ignoreRegexes: [String] {
    get { d.stringArray(forKey: "ignoreRegexes") ?? [] }
    set { d.set(newValue, forKey: "ignoreRegexes") }
  }

  /// Validierung NUR hier – leere/ungültige Muster werden nie gespeichert
  /// (Fix für den Maccy-Bug: leerer Regex brach die gesamte Ignore-Kette ab).
  static func validateRegex(_ pattern: String) -> Bool {
    guard !pattern.isEmpty else { return false }
    return (try? NSRegularExpression(pattern: pattern)) != nil
  }
}
