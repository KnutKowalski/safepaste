import AppKit
import CryptoKit
import Foundation

/// Überwacht das System-Pasteboard per Polling (changeCount) – wie Maccy,
/// aber ressourcenschonender (Timer-Toleranz) und mit allen Fixes.
final class PasteboardMonitor: NSObject {
  static let shared = PasteboardMonitor()

  var onNewRecord: ((ClipboardRecord) -> Void)?

  private var timer: Timer?
  private let pasteboard = NSPasteboard.general
  private var changeCount: Int = NSPasteboard.general.changeCount
  private var compiledRegexes: [NSRegularExpression] = []
  private var defaultsObserver: NSObjectProtocol?

  private let secretTypes: Set<NSPasteboard.PasteboardType> = [
    .concealed, .transient, .autoGenerated,
    NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    NSPasteboard.PasteboardType("net.antelle.keeweb"),
    NSPasteboard.PasteboardType("com.typeit4me.clipping"),
    NSPasteboard.PasteboardType("Pasteboard generator type")
  ]

  private let supportedTypes: Set<NSPasteboard.PasteboardType> = [
    .string, .rtf, .html, .png, .tiff, .jpegType, .heicType, .fileURL
  ]

  /// Größenlimit pro Eintrag (Maccy speichert beliebig große Blobs).
  private let maxItemBytes = 10 * 1024 * 1024

  func start() {
    recompileRegexes()
    defaultsObserver = NotificationCenter.default.addObserver(
      forName: UserDefaults.didChangeNotification,
      object: nil,
      queue: .main
    ) { [weak self] _ in
      self?.recompileRegexes()
      self?.scheduleTimer()
    }
    scheduleTimer()
  }

  private func scheduleTimer() {
    timer?.invalidate()
    let interval = AppSettings.checkInterval
    let t = Timer(timeInterval: interval, target: self,
                 selector: #selector(poll), userInfo: nil, repeats: true)
    t.tolerance = interval * 0.1 // spart Energie
    RunLoop.main.add(t, forMode: .common)
    timer = t
  }

  @objc private func poll() {
    let newCount = pasteboard.changeCount
    guard newCount != changeCount else { return }
    changeCount = newCount

    let types = Set(pasteboard.types ?? [])

    // Eigene Rückkopie nicht aufzeichnen.
    guard !types.contains(.safepasteRestored) else { return }

    // Verborgene/vergängliche/automatisch erzeugte Inhalte respektieren (Passwortmanager etc.).
    guard types.isDisjoint(with: secretTypes) else { return }
    guard !types.isDisjoint(with: supportedTypes) else { return }

    // Fix für den sourceApp-Timing-Bug: Die nspasteboard-Konvention ist
    // autoritativ; nur ohne Marker wird die Frontmost-App angenommen.
    var source = pasteboard.string(forType: .nspasteboardSource)
    if source != nil && source?.isEmpty == true { source = nil }
    if source == nil {
      source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    }
    if let source, AppSettings.ignoredApps.contains(source) {
      return
    }

    // Inhalte lesen (mit Größenlimit).
    var contents: [StoredContent] = []
    var totalBytes = 0
    for pasteItem in pasteboard.pasteboardItems ?? [] {
      for type in pasteItem.types {
        guard supportedTypes.contains(type), isPersistable(type) else { continue }
        guard let data = pasteItem.data(forType: type) else { continue }
        guard totalBytes + data.count <= maxItemBytes else {
          Log.error("Eintrag überschreitet Größenlimit (\(data.count) Bytes) – Typ übersprungen.")
          continue
        }
        totalBytes += data.count
        contents.append(StoredContent(type: type.rawValue, value: data))
      }
    }
    guard !contents.isEmpty else { return }

    if let text = pasteboard.string(forType: .string), matchesAnyIgnoreRegex(text) {
      return
    }

    let record = buildRecord(contents: contents, source: source)
    onNewRecord?(record)
  }

  private func isPersistable(_ type: NSPasteboard.PasteboardType) -> Bool {
    let raw = type.rawValue
    if raw.hasPrefix("dyn.") { return false }
    if raw.hasPrefix("com.microsoft.ole.source.") { return false }
    return true
  }

  /// Fix für den Maccy catch { return false }-Bug: ungültige Muster werden
  /// beim Kompilieren einzeln übersprungen; die Prüfung läuft immer komplett.
  private func matchesAnyIgnoreRegex(_ text: String) -> Bool {
    guard !compiledRegexes.isEmpty else { return false }
    let range = NSRange(text.startIndex..., in: text)
    for regex in compiledRegexes {
      if regex.firstMatch(in: text, range: range) != nil {
        return true
      }
    }
    return false
  }

  private func recompileRegexes() {
    compiledRegexes = AppSettings.ignoreRegexes.compactMap { pattern in
      guard let regex = try? NSRegularExpression(pattern: pattern) else {
        Log.error("Ungültiges Ignore-Muster gefunden und übersprungen (Länge \(pattern.count)).")
        return nil
      }
      return regex
    }
  }

  private func buildRecord(contents: [StoredContent], source: String?) -> ClipboardRecord {
    let imageRaw = [NSPasteboard.PasteboardType.png.rawValue,
                    NSPasteboard.PasteboardType.tiff.rawValue,
                    NSPasteboard.PasteboardType.jpegType.rawValue,
                    NSPasteboard.PasteboardType.heicType.rawValue]
    let hasImage = contents.contains { imageRaw.contains($0.type) }
    let hasFile = contents.contains { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }
    let hasRich = contents.contains {
      $0.type == NSPasteboard.PasteboardType.rtf.rawValue ||
      $0.type == NSPasteboard.PasteboardType.html.rawValue
    }
    let kind: ItemKind = hasImage ? .image : (hasFile ? .file : (hasRich ? .richText : .text))

    var preview = ""
    var fullText = ""
    if let stringContent = contents.first(where: { $0.type == NSPasteboard.PasteboardType.string.rawValue }) {
      let s = String(data: stringContent.value, encoding: .utf8) ?? ""
      preview = String(s.trimmingCharacters(in: .whitespacesAndNewlines).prefix(200))
      fullText = String(s.prefix(100_000)) // Volltextsuche über den GESAMTEN Inhalt
    }
    if preview.isEmpty && hasFile {
      let urls = contents
        .filter { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }
        .compactMap { URL(dataRepresentation: $0.value, relativeTo: nil, isAbsolute: true) }
      preview = urls.map(\.lastPathComponent).joined(separator: "\n")
    }
    if preview.isEmpty && hasImage { preview = "Bild" }
    if preview.isEmpty { preview = "Inhalt" }

    return ClipboardRecord(id: UUID(), kind: kind, contents: contents,
                           preview: preview, fullText: fullText,
                           sourceApp: source, copiedAt: Date())
  }
}
